#!/usr/bin/env node
/**
 * Generate build metadata for cache-busted script loading and production diagnostics.
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
import { execSync } from "child_process";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const BUILD_JSON = path.join(ROOT, "data", "build-info.json");
const BUILD_JS = path.join(ROOT, "design-system", "js", "wds-build.js");
const LOADER_VERSION = 2;
const LOCATION_SCHEMA = 3;

function gitShortSha() {
  try {
    return execSync("git rev-parse --short HEAD", { cwd: ROOT, encoding: "utf8" }).trim();
  } catch {
    return "unknown";
  }
}

function gitFullSha() {
  try {
    return execSync("git rev-parse HEAD", { cwd: ROOT, encoding: "utf8" }).trim();
  } catch {
    return "unknown";
  }
}

function updateHtmlFiles(sha) {
  const htmlFiles = [
    "index.html",
    "kiosk.html",
    "debug.html",
    "status.html",
    "design-system/patterns/product-shell.html",
    "design-system/content-engine/demo.html",
    "design-system/ecosystem/product-home-shell.html"
  ];
  htmlFiles.forEach((rel) => {
    const file = path.join(ROOT, rel);
    if (!fs.existsSync(file)) return;
    let html = fs.readFileSync(file, "utf8");
    const next = html
      .replace(/__WAYPOINT_BUILD_SHA__/g, sha)
      .replace(/\?v=[a-f0-9]{7,40}/gi, "?v=" + sha)
      .replace(/(src="[^"]+\.js)(?!\?v=)/g, (match, prefix) => {
        if (prefix.includes("fonts.googleapis") || prefix.includes("gstatic")) return match;
        if (/wds-build\.js|wds\.js|wds-platform\.js|home-boot\.js|kiosk-boot\.js|kiosk\.js/.test(prefix)) {
          return prefix + "?v=" + sha;
        }
        return match;
      });
    if (next !== html) {
      fs.writeFileSync(file, next, "utf8");
      console.log("updated", rel);
    }
  });
}

function main() {
  const commit = gitShortSha();
  const commitFull = gitFullSha();
  const deployedAt = new Date().toISOString();
  const info = {
    commit,
    commitFull,
    deployedAt,
    locationSchema: LOCATION_SCHEMA,
    loaderVersion: LOADER_VERSION
  };

  fs.mkdirSync(path.dirname(BUILD_JSON), { recursive: true });
  fs.writeFileSync(BUILD_JSON, JSON.stringify(info, null, 2) + "\n", "utf8");

  const js = `/**
 * Waypoint build metadata — generated by scripts/generate-build-info.mjs
 * Do not edit manually.
 */
(function (global) {
  "use strict";
  var BUILD = ${JSON.stringify(info, null, 2)};
  var scriptLoads = [];

  function getVersionQuery() {
    return BUILD && BUILD.commit ? "?v=" + BUILD.commit : "";
  }

  function trackScript(scriptEl) {
    if (!scriptEl || !scriptEl.src) return;
    var entry = {
      url: scriptEl.src,
      startedAt: new Date().toISOString(),
      status: "pending",
      cacheSource: "network"
    };
    scriptLoads.push(entry);
    scriptEl.addEventListener("load", function () {
      entry.status = "loaded";
      entry.loadedAt = new Date().toISOString();
    });
    scriptEl.addEventListener("error", function () {
      entry.status = "error";
      entry.loadedAt = new Date().toISOString();
    });
  }

  function expose() {
    global.__WAYPOINT_BUILD__ = {
      commit: BUILD.commit,
      commitFull: BUILD.commitFull,
      deployedAt: BUILD.deployedAt,
      locationSchema: BUILD.locationSchema,
      loaderVersion: BUILD.loaderVersion
    };
    global.WDS = global.WDS || {};
    global.WDS.build = {
      info: BUILD,
      getVersionQuery: getVersionQuery,
      trackScript: trackScript,
      getScriptLoads: function () { return scriptLoads.slice(); }
    };
  }

  expose();
})(typeof window !== "undefined" ? window : globalThis);
`;

  fs.writeFileSync(BUILD_JS, js, "utf8");
  updateHtmlFiles(commit);
  console.log("build-info", commit, deployedAt);
}

main();
